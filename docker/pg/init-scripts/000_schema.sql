-- 用户表
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    login_id VARCHAR(16) NOT NULL UNIQUE,
    nickname VARCHAR(16) NOT NULL,
    role INTEGER NOT NULL,
    -- bcrypt 哈希值
    password_hash VARCHAR(72) NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE users IS '用户表';
COMMENT ON COLUMN users.role IS '用户角色：学生=1，教师=2，系统管理员=3';
COMMENT ON COLUMN users.id IS '用户内部ID';
COMMENT ON COLUMN users.login_id IS '用户登录ID';

CREATE TABLE IF NOT EXISTS classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    owner BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(16) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ(3)
);

COMMENT ON TABLE classes IS '班级表';
COMMENT ON COLUMN classes.owner IS '班级所属教师用户 ID';
COMMENT ON COLUMN classes.name IS '班级名称';
COMMENT ON COLUMN classes.description IS '班级简介';
COMMENT ON COLUMN classes.deleted_at IS '软删除时间，NULL 表示班级有效';

CREATE INDEX IF NOT EXISTS idx_classes_owner ON classes(owner);

CREATE TABLE IF NOT EXISTS class_members (
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL,
    joined_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (class_id, user_id)
);

COMMENT ON TABLE class_members IS '班级学生成员关系表';
COMMENT ON COLUMN class_members.class_id IS '班级 ID';
COMMENT ON COLUMN class_members.user_id IS '学生用户 ID';
COMMENT ON COLUMN class_members.joined_at IS '加入班级时间';

CREATE INDEX IF NOT EXISTS idx_class_members_user_id ON class_members(user_id);

CREATE TABLE IF NOT EXISTS class_invites (
    class_id BIGINT PRIMARY KEY REFERENCES classes(id) ON DELETE CASCADE,
    invite_code UUID NOT NULL UNIQUE,
    passphrase VARCHAR(16),
    expires_at TIMESTAMPTZ(3) NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_class_invites_invite_code ON class_invites(invite_code);

COMMENT ON TABLE class_invites IS '班级加入邀请表';
COMMENT ON COLUMN class_invites.invite_code IS 'UUIDv7 格式的分享邀请码，由应用生成';
COMMENT ON COLUMN class_invites.passphrase IS '可选的明文加入暗号';
COMMENT ON COLUMN class_invites.expires_at IS '邀请过期时间，默认创建后 7 天';

-- 文章独立保存，本阶段每个新任务创建一篇新文章。
CREATE TABLE IF NOT EXISTS articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    content TEXT NOT NULL,
    uploaded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    uploaded_in_class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_articles_content CHECK (
        char_length(content) BETWEEN 1 AND 5000
        AND content ~ '[^[:space:]]'
    )
);

COMMENT ON TABLE articles IS '阅读文章';
COMMENT ON COLUMN articles.content IS '文章正文，最多 5000 字且不能全为空白';
COMMENT ON COLUMN articles.uploaded_by IS '首次上传教师用户 ID，由登录身份确定';
COMMENT ON COLUMN articles.uploaded_in_class_id IS '首次上传时的班级 ID，后续引用不覆盖';
COMMENT ON COLUMN articles.updated_at IS '正文最近修改时间，由业务写入时显式更新';

-- 阅读任务创建即发布；文章 ID 不设唯一约束，为未来复用留出空间。
CREATE TABLE IF NOT EXISTS reading_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE RESTRICT,
    published_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title VARCHAR(50) NOT NULL,
    requirements TEXT,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reading_tasks_title CHECK (title ~ '[^[:space:]]')
);

CREATE INDEX IF NOT EXISTS idx_reading_tasks_class_id_id
    ON reading_tasks(class_id, id);
CREATE INDEX IF NOT EXISTS idx_reading_tasks_article_id
    ON reading_tasks(article_id);

COMMENT ON TABLE reading_tasks IS '班级阅读任务';
COMMENT ON COLUMN reading_tasks.class_id IS '任务所属班级 ID';
COMMENT ON COLUMN reading_tasks.article_id IS '文章 ID，任务与文章分别保存';
COMMENT ON COLUMN reading_tasks.published_by IS '首次发布教师用户 ID，由登录身份确定';
COMMENT ON COLUMN reading_tasks.title IS '任务标题，最多 50 字且不能全为空白';
COMMENT ON COLUMN reading_tasks.requirements IS '可选阅读要求，不单独限制字数';
COMMENT ON COLUMN reading_tasks.updated_at IS '标题、阅读要求或正文最近修改时间，由业务显式更新';

-- 每名学生在每个任务中保留一条累计统计，退班不删除。
CREATE TABLE IF NOT EXISTS reading_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    task_id BIGINT NOT NULL REFERENCES reading_tasks(id) ON DELETE RESTRICT,
    reading_duration_seconds BIGINT NOT NULL DEFAULT 0,
    lookup_count INTEGER NOT NULL DEFAULT 0,
    new_sense_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reading_stats_student_task UNIQUE (student_id, task_id),
    CONSTRAINT ck_reading_stats_duration CHECK (reading_duration_seconds >= 0),
    CONSTRAINT ck_reading_stats_lookup_count CHECK (lookup_count >= 0),
    CONSTRAINT ck_reading_stats_new_sense_count CHECK (new_sense_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_reading_stats_task_student
    ON reading_stats(task_id, student_id);

COMMENT ON TABLE reading_stats IS '学生在阅读任务中的累计统计';
COMMENT ON COLUMN reading_stats.student_id IS '学生用户 ID，不依赖当前班级成员关系';
COMMENT ON COLUMN reading_stats.task_id IS '阅读任务 ID';
COMMENT ON COLUMN reading_stats.reading_duration_seconds IS '累计阅读秒数，不保存分段明细';
COMMENT ON COLUMN reading_stats.lookup_count IS '有效主动查词次数，网络重试不得重复累计';
COMMENT ON COLUMN reading_stats.new_sense_count IS '首次在本任务加入的学习释义数，与首次建卡在同一事务递增';
COMMENT ON COLUMN reading_stats.updated_at IS '最近成功统计更新时间，由业务写入时显式更新';

